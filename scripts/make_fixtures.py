"""Write the Python-generated data the JavaScript engine is checked against (and the one table it needs).

    python scripts/make_fixtures.py

Writes:
    web/static/fractal_quirks.js        cells where SciPy's savgol result rounds below the exact value (engine data)
    tests/fixtures/fractal_degrees.json  every emotion's scale-degree grid from the Python generator
    tests/fixtures/compositions.json     CASES composed by the Python CreativeComposer (notes, sections, MIDI)
    tests/fixtures/random_streams.json   draws from CPython's random and NumPy's legacy generator for some seeds
tests/test_fixtures_current.py checks that these still match the Python code.
"""
import hashlib
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from web.compose import compose  # noqa: E402
from web.fractal import python_degrees, quirks  # noqa: E402

EMOTIONS = ["ethereal", "dark", "joyful", "melancholic", "energetic", "peaceful"]
FORMS = ["sonata", "rondo", "theme_and_variations", "fugue", "minimalist", "through_composed", "aleatoric",
         "mixed", "arch", "moment", "process"]
CASES = [{"form": f, "seed": s} for f in FORMS for s in (0, 7)] + [
    {"form": "mixed", "seed": 3, "mode": "dorian", "section_count": 9, "voice_count": 6, "base_tempo": 90,
     "emotional_journey": ["dark", "ethereal", "joyful", "melancholic", "energetic", "peaceful"]},
    {"form": "aleatoric", "seed": 2**32 - 1, "mode": "locrian", "key": "Eb", "voice_count": 2,
     "emotional_journey": ["joyful"]},
    {"form": "moment", "seed": 123456, "mode": "lydian", "section_count": 12, "voice_count": 1, "base_tempo": 200},
    {"form": "process", "seed": 5, "mode": "phrygian", "section_count": 3, "voice_count": 3, "base_tempo": 45},
    {"form": "sonata", "seed": 11, "mode": "mixolydian", "key": "F#", "voice_count": 8},
    {"form": "sonata", "seed": 21, "key": "Bb", "development_complexity": 1.0, "texture_density": 1.0,
     "modulation_frequency": 1.0},
    {"form": "mixed", "seed": 8, "key": "E", "development_complexity": 0.625, "texture_density": 0.5,
     "modulation_frequency": 0.75, "section_count": 10, "voice_count": 5},
    {"form": "arch", "seed": 13, "key": "F#", "development_complexity": 0.0, "texture_density": 0.0,
     "modulation_frequency": 0.0},
    {"form": "through_composed", "seed": 99, "mode": "aeolian",
     "emotional_journey": ["melancholic", "dark", "dark", "ethereal", "peaceful", "joyful", "energetic", "dark"]},
]


def random_streams():
    import random
    import numpy as np
    out = {}
    for seed in (0, 1, 42, 2**32 - 1, 123456789012):
        r = random.Random(seed)
        d = {"random": [r.random() for _ in range(5)], "randint": [r.randint(0, 9) for _ in range(20)],
             "choice": [r.choice(range(7)) for _ in range(20)], "uniform": [r.uniform(0.8, 1.2) for _ in range(5)],
             "sample24": r.sample(range(24), 3), "sample12": r.sample(range(12), 3)}
        if seed < 2**32:
            np.random.seed(seed)
            d["np_randint"] = [int(np.random.randint(40, 60)) for _ in range(30)] + \
                [int(np.random.randint(0, 1000)) for _ in range(10)]
        out[str(seed)] = d
    return out


def degrees_text(grid):
    return "".join("0123456789abcd"[v] for row in grid for v in row)


def build_compositions():
    out = []
    for case in CASES:
        r = compose(case)
        notes_json = json.dumps(r["notes"], separators=(",", ":"))
        out.append({"case": case, "params": r["params"], "form": r["form"], "sections": r["sections"],
                    "n_notes": len(r["notes"]), "notes_sha256": hashlib.sha256(notes_json.encode()).hexdigest(),
                    "first_notes": r["notes"][:40], "midi_base64": r["midi_base64"]})
    return out


def quirks_js(table):
    lines = ["// Generated by scripts/make_fixtures.py from the Python generator: do not edit.",
             "// [row, column, degree] cells where scipy.signal.savgol_filter (floating point) gives a different scale",
             "// degree from the exact smoothing in fractal_engine.js (its value lands one ulp below a whole number).",
             "export const QUIRKS = {"]
    for e in EMOTIONS:
        lines.append(f"  {e}: {json.dumps([list(q) for q in table[e]], separators=(',', ':'))},")
    lines.append("};")
    return "\n".join(lines) + "\n"


def main():
    table = {e: quirks(e) for e in EMOTIONS}
    (ROOT / "web/static/fractal_quirks.js").write_text(quirks_js(table))
    fx = ROOT / "tests/fixtures"
    fx.mkdir(parents=True, exist_ok=True)
    (fx / "fractal_degrees.json").write_text(json.dumps({e: degrees_text(python_degrees(e)) for e in EMOTIONS}))
    (fx / "random_streams.json").write_text(json.dumps(random_streams()))
    comps = build_compositions()
    (fx / "compositions.json").write_text(json.dumps(comps, separators=(",", ":")))
    print(f"quirks: {sum(len(v) for v in table.values())} cells; compositions: {len(comps)} cases, "
          f"{sum(c['n_notes'] for c in comps)} notes")


if __name__ == "__main__":
    main()
